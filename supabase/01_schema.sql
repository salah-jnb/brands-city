-- Vrai si l'utilisateur connecté est admin (security definer : évite la
-- récursion RLS sur profiles).
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'Admin'
  );
$$;

-- Chaque nouvel utilisateur Auth reçoit automatiquement un profil 'Client'.
-- Le rôle ne vient JAMAIS des métadonnées envoyées par le client.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (new.id, new.email, 'Client')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

