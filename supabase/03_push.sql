-- =====================================================================
--  Notifications push : abonnements des appareils admin + envoi à chaque
--  nouvelle commande. À exécuter APRÈS 01_schema.sql et 02_data.sql.
--
--  Fonctionnement : create_order() appelle private.notify_new_order(), qui
--  poste (via pg_net, en asynchrone) les abonnements + les infos de la
--  commande vers /api/notify-order (fonction Vercel), qui signe et envoie
--  la notification Web Push. Un échec de notification n'annule JAMAIS
--  une commande.
--
--  Après exécution, renseigner l'URL et le secret (une seule fois) :
--    insert into private.settings (key, value) values
--      ('notify_url',    'https://VOTRE-SITE.vercel.app/api/notify-order'),
--      ('notify_secret', '<même valeur que WEBHOOK_SECRET sur Vercel>')
--    on conflict (key) do update set value = excluded.value;
-- =====================================================================

create extension if not exists pg_net;

-- ---------------------------------------------------------------------
-- 1. Abonnements push (un par appareil admin)
-- ---------------------------------------------------------------------
create table if not exists public.push_subscriptions (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users (id) on delete cascade,
  endpoint   text not null unique,
  p256dh     text not null,
  auth       text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_push_subscriptions_user on public.push_subscriptions (user_id);

alter table public.push_subscriptions enable row level security;

-- Seuls les admins peuvent enregistrer / voir / supprimer LEURS appareils.
create policy "push_select_own" on public.push_subscriptions
  for select to authenticated
  using (user_id = auth.uid() and public.is_admin());
create policy "push_insert_own" on public.push_subscriptions
  for insert to authenticated
  with check (user_id = auth.uid() and public.is_admin());
create policy "push_update_own" on public.push_subscriptions
  for update to authenticated
  using (user_id = auth.uid() and public.is_admin())
  with check (user_id = auth.uid() and public.is_admin());
create policy "push_delete_own" on public.push_subscriptions
  for delete to authenticated
  using (user_id = auth.uid() and public.is_admin());

-- ---------------------------------------------------------------------
-- 2. Réglages privés (URL + secret) : inaccessibles depuis l'API
-- ---------------------------------------------------------------------
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table if not exists private.settings (
  key   text primary key,
  value text not null
);
revoke all on private.settings from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- 3. Envoi de la notification
-- ---------------------------------------------------------------------
create or replace function private.notify_new_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = public, private, extensions
as $$
declare
  v_url    text;
  v_secret text;
  v_subs   jsonb;
  v_total  numeric;
  v_items  integer;
begin
  select value into v_url    from private.settings where key = 'notify_url';
  select value into v_secret from private.settings where key = 'notify_secret';
  if v_url is null or v_secret is null then return; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'endpoint', endpoint,
           'keys', jsonb_build_object('p256dh', p256dh, 'auth', auth))), '[]'::jsonb)
    into v_subs
    from public.push_subscriptions;
  if jsonb_array_length(v_subs) = 0 then return; end if;

  select total_amount into v_total from public.orders where id = p_order_id;
  select coalesce(sum(quantity), 0) into v_items from public.order_items where order_id = p_order_id;

  perform net.http_post(
    url     := v_url,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', v_secret),
    body    := jsonb_build_object(
                 'orderId', p_order_id,
                 'total', v_total,
                 'items', v_items,
                 'subscriptions', v_subs)
  );
end;
$$;
revoke all on function private.notify_new_order(bigint) from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- 4. create_order() : identique à 01_schema.sql + notification à la fin
-- ---------------------------------------------------------------------
create or replace function public.create_order()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_cart  bigint;
  v_order bigint;
  v_total numeric(10,2);
  v_stock integer;
  r       record;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;

  select id into v_cart from carts where user_id = v_uid;
  if v_cart is null or not exists (select 1 from cart_items where cart_id = v_cart) then
    raise exception 'Cart is empty';
  end if;

  insert into orders (user_id, status, total_amount)
  values (v_uid, 'Pending', 0)
  returning id into v_order;

  for r in
    select ci.shoe_id, ci.color_id, ci.size, ci.quantity, s.name, s.price
      from cart_items ci
      join shoes s on s.id = ci.shoe_id
     where ci.cart_id = v_cart
     order by ci.id
  loop
    select quantity into v_stock from shoe_sizes
     where shoe_id = r.shoe_id and size = r.size
     for update;

    if not found then
      raise exception 'Size % not available for %', r.size, r.name;
    end if;
    if v_stock < r.quantity then
      raise exception 'Not enough stock for % size %', r.name, r.size;
    end if;

    update shoe_sizes set quantity = quantity - r.quantity
     where shoe_id = r.shoe_id and size = r.size;

    insert into order_items (order_id, shoe_id, color_id, size, quantity, price)
    values (v_order, r.shoe_id, r.color_id, r.size, r.quantity, r.price);
  end loop;

  select coalesce(sum(price * quantity), 0) into v_total
    from order_items where order_id = v_order;
  update orders set total_amount = v_total where id = v_order;

  delete from cart_items where cart_id = v_cart;

  -- Notification push aux admins : ne doit jamais faire échouer la commande
  begin
    perform private.notify_new_order(v_order);
  exception when others then
    null;
  end;

  return v_order;
end;
$$;
