-- Profil + rôle de chaque utilisateur (lié à Supabase Auth).
-- Le rôle n'est modifiable par personne via l'API (aucune policy d'écriture).
create table public.profiles (
  id    uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  role  text not null default 'Client' check (role in ('Client', 'Admin'))
);

create table public.shoes (
  id        bigint generated by default as identity primary key,
  name      varchar(100)  not null,
  brand     varchar(50)   not null,
  price     numeric(10,2) not null check (price >= 0),
  image_url varchar(500)
);
create index idx_shoes_brand on public.shoes (brand);

create table public.shoe_colors (
  id         bigint generated by default as identity primary key,
  shoe_id    bigint      not null references public.shoes (id) on delete cascade,
  color_name varchar(50) not null,
  color_code varchar(7)  not null,
  image_url  varchar(500)
);
create index idx_shoe_colors_shoe on public.shoe_colors (shoe_id);

create table public.shoe_sizes (
  id       bigint generated by default as identity primary key,
  shoe_id  bigint  not null references public.shoes (id) on delete cascade,
  size     integer not null,
  quantity integer not null default 0 check (quantity >= 0),
  unique (shoe_id, size)
);
create index idx_shoe_sizes_shoe on public.shoe_sizes (shoe_id);

create table public.carts (
  id      bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users (id) on delete cascade
);

create table public.cart_items (
  id       bigint generated by default as identity primary key,
  cart_id  bigint  not null references public.carts (id) on delete cascade,
  shoe_id  bigint  not null references public.shoes (id) on delete cascade,
  color_id bigint  references public.shoe_colors (id) on delete set null,
  size     integer not null,
  quantity integer not null check (quantity > 0)
);
create index idx_cart_items_cart  on public.cart_items (cart_id);
create index idx_cart_items_shoe  on public.cart_items (shoe_id);
create index idx_cart_items_color on public.cart_items (color_id);

create table public.orders (
  id           bigint generated by default as identity primary key,
  user_id      uuid          not null references auth.users (id) on delete cascade,
  order_date   timestamptz   not null default now(),
  status       varchar(20)   not null default 'Pending'
               check (status in ('Pending', 'Confirmed', 'Shipped', 'Delivered', 'Cancelled')),
  total_amount numeric(10,2) not null
);
create index idx_orders_user   on public.orders (user_id);
create index idx_orders_status on public.orders (status);
create index idx_orders_date   on public.orders (order_date);

create table public.order_items (
  id       bigint generated by default as identity primary key,
  order_id bigint        not null references public.orders (id) on delete cascade,
  shoe_id  bigint        not null references public.shoes (id) on delete cascade,
  color_id bigint        references public.shoe_colors (id) on delete set null,
  size     integer       not null,
  quantity integer       not null check (quantity > 0),
  price    numeric(10,2) not null
);
create index idx_order_items_order on public.order_items (order_id);
create index idx_order_items_shoe  on public.order_items (shoe_id);
create index idx_order_items_color on public.order_items (color_id);

