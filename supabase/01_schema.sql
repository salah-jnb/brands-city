-- 3. ROW LEVEL SECURITY
-- ---------------------------------------------------------------------
alter table public.profiles    enable row level security;
alter table public.shoes       enable row level security;
alter table public.shoe_colors enable row level security;
alter table public.shoe_sizes  enable row level security;
alter table public.carts       enable row level security;
alter table public.cart_items  enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

-- profiles : lecture de son propre profil (ou tous si admin). Pas d'écriture.
create policy "profiles_select" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

-- Catalogue : lecture publique, écriture réservée aux admins.
create policy "shoes_read"  on public.shoes       for select using (true);
create policy "colors_read" on public.shoe_colors for select using (true);
create policy "sizes_read"  on public.shoe_sizes  for select using (true);

create policy "shoes_admin_write"  on public.shoes
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "colors_admin_write" on public.shoe_colors
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "sizes_admin_write"  on public.shoe_sizes
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Panier : chacun accède uniquement au sien.
create policy "carts_owner" on public.carts
  for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "cart_items_owner" on public.cart_items
  for all to authenticated
  using (exists (select 1 from public.carts c where c.id = cart_id and c.user_id = auth.uid()))
  with check (exists (select 1 from public.carts c where c.id = cart_id and c.user_id = auth.uid()));

-- Commandes : lecture des siennes (ou toutes si admin), changement de statut
-- par l'admin uniquement. La création passe EXCLUSIVEMENT par create_order().
create policy "orders_select" on public.orders
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

create policy "orders_admin_update" on public.orders
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create policy "order_items_select" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_id and (o.user_id = auth.uid() or public.is_admin())
  ));

