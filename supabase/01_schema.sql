-- Ajoute un article au panier (vérifie couleur, taille et stock).
create or replace function public.add_to_cart(
  p_shoe_id  bigint,
  p_color_id bigint,
  p_size     integer,
  p_quantity integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_cart  bigint;
  v_stock integer;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;
  if p_quantity is null or p_quantity < 1 then raise exception 'Invalid quantity'; end if;

  if not exists (select 1 from shoe_colors where id = p_color_id and shoe_id = p_shoe_id) then
    raise exception 'Color not found';
  end if;

  select quantity into v_stock from shoe_sizes
   where shoe_id = p_shoe_id and size = p_size;
  if not found then raise exception 'Size not available'; end if;
  if v_stock < p_quantity then raise exception 'Not enough stock'; end if;

  insert into carts (user_id) values (v_uid) on conflict (user_id) do nothing;
  select id into v_cart from carts where user_id = v_uid;

  update cart_items
     set quantity = quantity + p_quantity
   where cart_id = v_cart and shoe_id = p_shoe_id
     and size = p_size and color_id is not distinct from p_color_id;

  if not found then
    insert into cart_items (cart_id, shoe_id, color_id, size, quantity)
    values (v_cart, p_shoe_id, p_color_id, p_size, p_quantity);
  end if;
end;
$$;

-- Crée une commande à partir du panier, de façon atomique :
-- vérifie/décrémente le stock, calcule le total CÔTÉ SERVEUR
-- (prix lus dans la table shoes), puis vide le panier.
create or replace function public.create_order()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_cart  bigint;
  v_order bigint;
  v_total numeric(10,2);
  v_stock integer;
  r       record;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;

  select id into v_cart from carts where user_id = v_uid;
  if v_cart is null or not exists (select 1 from cart_items where cart_id = v_cart) then
    raise exception 'Cart is empty';
  end if;

  insert into orders (user_id, status, total_amount)
  values (v_uid, 'Pending', 0)
  returning id into v_order;

  for r in
    select ci.shoe_id, ci.color_id, ci.size, ci.quantity, s.name, s.price
      from cart_items ci
      join shoes s on s.id = ci.shoe_id
     where ci.cart_id = v_cart
     order by ci.id
  loop
    select quantity into v_stock from shoe_sizes
     where shoe_id = r.shoe_id and size = r.size
     for update;

    if not found then
      raise exception 'Size % not available for %', r.size, r.name;
    end if;
    if v_stock < r.quantity then
      raise exception 'Not enough stock for % size %', r.name, r.size;
    end if;

    update shoe_sizes set quantity = quantity - r.quantity
     where shoe_id = r.shoe_id and size = r.size;

    insert into order_items (order_id, shoe_id, color_id, size, quantity, price)
    values (v_order, r.shoe_id, r.color_id, r.size, r.quantity, r.price);
  end loop;

  select coalesce(sum(price * quantity), 0) into v_total
    from order_items where order_id = v_order;
  update orders set total_amount = v_total where id = v_order;

  delete from cart_items where cart_id = v_cart;

  return v_order;
end;
$$;

-- Seuls les utilisateurs connectés peuvent appeler ces fonctions.
revoke all on function public.add_to_cart(bigint, bigint, integer, integer) from public, anon;
revoke all on function public.create_order() from public, anon;
grant execute on function public.add_to_cart(bigint, bigint, integer, integer) to authenticated;
grant execute on function public.create_order() to authenticated;

-- ---------------------------------------------------------------------
-- 5. STORAGE (images) : bucket public "shoes"
--    Lecture publique, écriture/suppression réservées aux admins.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('shoes', 'shoes', true)
on conflict (id) do nothing;

create policy "shoes_images_read" on storage.objects
  for select using (bucket_id = 'shoes');

create policy "shoes_images_admin_insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'shoes' and public.is_admin());

create policy "shoes_images_admin_update" on storage.objects
  for update to authenticated
  using (bucket_id = 'shoes' and public.is_admin());

create policy "shoes_images_admin_delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'shoes' and public.is_admin());
